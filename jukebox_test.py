# --------------------------------------------------------------------------- #
# Obraz -> macierz (obsługa wielu formatów)
# --------------------------------------------------------------------------- #
def _pil_to_gray(img):
    """PIL Image -> float32 2D. Zachowuje zakres 16-bit, składa alfę na czarnym tle."""
    img = ImageOps.exif_transpose(img)

    if img.mode in ("I;16", "I;16L", "I;16B", "I;16N", "I", "F"):
        return np.asarray(img).astype(np.float32)

    if img.mode in ("RGBA", "LA", "PA") or "transparency" in img.info:
        rgba = img.convert("RGBA")
        bg = Image.new("RGBA", rgba.size, (0, 0, 0, 255))
        img = Image.alpha_composite(bg, rgba)

    return np.asarray(img.convert("L"), dtype=np.float32)


def _read_fits(path):
    try:
        from astropy.io import fits
    except ImportError:
        raise ImportError("Do plików FITS zainstaluj:  pip install astropy")
    with fits.open(path) as hdul:
        for hdu in hdul:
            data = getattr(hdu, "data", None)
            if data is not None and np.ndim(data) >= 2:
                data = np.squeeze(np.asarray(data))
                while data.ndim > 2:
                    data = data[0]
                data = np.nan_to_num(data.astype(np.float32))
                return [data[::-1]]  # FITS: początek układu w lewym dolnym rogu
    raise ValueError(f"Brak danych obrazu w {path}")


def read_gray_frames(path, all_frames=False):
    """Zwraca listę tablic 2D (float32)."""
    path = Path(path)
    ext = path.suffix.lower()

    if ext in FITS_EXT:
        return _read_fits(path)

    if ext in NPY_EXT:
        arr = np.squeeze(np.load(path)).astype(np.float32)
        if arr.ndim == 3:
            arr = arr.mean(axis=-1)
        if arr.ndim != 2:
            raise ValueError(f"Plik .npy musi zawierać obraz 2D/3D: {path}")
        return [np.nan_to_num(arr)]

    with Image.open(path) as img:
        if all_frames and getattr(img, "n_frames", 1) > 1:
            return [_pil_to_gray(f.copy()) for f in ImageSequence.Iterator(img)]
        return [_pil_to_gray(img)]


def _to_matrix(arr, columns, rows, low_pct=1.0, high_pct=99.5):
    im = Image.fromarray(np.ascontiguousarray(arr, dtype=np.float32))  # tryb "F"
    im = im.resize((columns, rows), _BOX)  # uśrednianie bloków pikseli
    m = np.asarray(im, dtype=np.float64)

    lo, hi = np.percentile(m, [low_pct, high_pct])
    if hi - lo < 1e-9:
        return np.zeros_like(m)
    return np.clip((m - lo) / (hi - lo), 0.0, 1.0)


def load_matrices(path, columns, rows, low_pct=1.0, high_pct=99.5,
                  all_frames=False):
    """Jeden plik -> lista macierzy (>1 tylko przy all_frames i animacjach)."""
    return [_to_matrix(a, columns, rows, low_pct, high_pct)
            for a in read_gray_frames(path, all_frames)]


def load_matrix(path, columns, rows, low_pct=1.0, high_pct=99.5):
    """Zgodne ze starym API: jedna macierz (rows x columns), 0..1."""
    return load_matrices(path, columns, rows, low_pct, high_pct)[0]


def collect_images(source):
    """Plik lub folder -> posortowana lista obsługiwanych plików graficznych."""
    p = Path(source)
    if p.is_dir():
        files = sorted(f for f in p.iterdir()
                       if f.is_file() and f.suffix.lower() in IMG_EXT)
    elif p.is_file() and p.suffix.lower() in IMG_EXT:
        files = [p]
    elif not p.exists():
        raise FileNotFoundError(f"Nie znaleziono: {source}")
    else:
        raise ValueError(f"Nieobsługiwany format: {p.suffix}. "
                         f"Obsługiwane: {', '.join(sorted(IMG_EXT))}")
    if not files:
        raise FileNotFoundError(f"Brak obrazów w {source}")
    return files


def load_all(source, columns, rows, low_pct=1.0, high_pct=99.5, all_frames=False):
    """Plik/folder -> lista macierzy gotowa do render_frames()."""
    mats = []
    for f in collect_images(source):
        mats += load_matrices(f, columns, rows, low_pct, high_pct, all_frames)
    return mats


# --------------------------------------------------------------------------- #
# Skale / wysokości dźwięków
# --------------------------------------------------------------------------- #
def row_to_midi(rows, scale, root_midi):
    """Lista numerów MIDI dla każdego wiersza (0 = góra obrazu = najwyższy dźwięk)."""
    notes = []
    for i in range(rows):
        octave, degree = divmod(i, len(scale))
        notes.append(root_midi + 12 * octave + scale[degree])
    return notes[::-1]


def midi_to_freq(m):
    return 440.0 * 2 ** ((m - 69) / 12.0)


# --------------------------------------------------------------------------- #
# Synteza dźwięku
# --------------------------------------------------------------------------- #
def synth_note(freq, duration, amp, harmonics=(1.0, 0.45, 0.25, 0.12)):
    """Dźwięk addytywny (kilka harmonicznych) z prostą obwiednią."""
    n = int(duration * SAMPLE_RATE)
    t = np.arange(n) / SAMPLE_RATE
    wave_ = np.zeros(n)
    for k, h in enumerate(harmonics, start=1):
        if freq * k < SAMPLE_RATE / 2:
            wave_ += h * np.sin(2 * np.pi * freq * k * t)
    attack = 0.01
    env = np.minimum(t / attack, 1.0) * np.exp(-t / (duration * 0.35))
    fade = min(int(0.01 * SAMPLE_RATE), n)
    if fade > 0:
        env[-fade:] *= np.linspace(1, 0, fade)
    return amp * wave_ * env


def render_frames(matrices, midi_notes, note_len, max_voices, threshold, gamma,
                  tail_factor=3.0):
    """Lista macierzy (klatek) -> stereo audio (N x 2)."""
    rows, cols = matrices[0].shape
    total_cols = cols * len(matrices)
    step = int(note_len * SAMPLE_RATE)
    tail = int(note_len * tail_factor * SAMPLE_RATE)
    out = np.zeros((total_cols * step + tail + SAMPLE_RATE, 2))

    freqs = [midi_to_freq(m) for m in midi_notes]
    pans = np.linspace(0.2, 0.8, rows)[::-1]  # niskie w lewo, wysokie w prawo

    col_idx = 0
    for mat in matrices:
        for c in range(cols):
            column = mat[:, c]
            candidates = np.argsort(column)[::-1][:max_voices]
            for r in candidates:
                v = column[r]
                if v < threshold:
                    continue
                amp = (v ** gamma) / max_voices
                note = synth_note(freqs[r], note_len * tail_factor, amp)
                start = col_idx * step
                end = start + len(note)
                left = np.cos(pans[r] * np.pi / 2)
                right = np.sin(pans[r] * np.pi / 2)
                out[start:end, 0] += note * left
                out[start:end, 1] += note * right
            col_idx += 1
    return out


def add_reverb(audio, decay=0.35, delays_ms=(37, 53, 79, 113)):
    """Prosty pogłos (opóźnione kopie)."""
    out = audio.copy()
    for i, d in enumerate(delays_ms):
        shift = max(1, int(d / 1000 * SAMPLE_RATE))
        if shift >= len(audio):
            continue
        out[shift:] += (decay ** (i + 1)) * audio[:-shift]
    return out


def save_wav(path, audio):
    peak = np.max(np.abs(audio))
    if peak > 0:
        audio = audio / peak * 0.9
    data = (audio * 32767).astype(np.int16)
    with wave.open(str(path), "wb") as f:
        f.setnchannels(2)
        f.setsampwidth(2)
        f.setframerate(SAMPLE_RATE)
        f.writeframes(data.tobytes())


# --------------------------------------------------------------------------- #
# Opcjonalny eksport MIDI
# --------------------------------------------------------------------------- #
def save_midi(path, matrices, midi_notes, note_len, max_voices, threshold):
    try:
        import mido
    except ImportError:
        print("Aby zapisać MIDI zainstaluj:  pip install mido", file=sys.stderr)
        return False
    tpb = 480
    mid = mido.MidiFile(ticks_per_beat=tpb)
    track = mido.MidiTrack()
    mid.tracks.append(track)
    bpm = 60.0 / note_len  # jedna kolumna = jedno uderzenie
    track.append(mido.MetaMessage("set_tempo", tempo=mido.bpm2tempo(bpm)))

    for mat in matrices:
        for c in range(mat.shape[1]):
            column = mat[:, c]
            chosen = [r for r in np.argsort(column)[::-1][:max_voices]
                      if column[r] >= threshold]
            for r in chosen:
                vel = int(30 + 97 * column[r])
                track.append(mido.Message("note_on", note=int(midi_notes[r]),
                                          velocity=vel, time=0))
            for i, r in enumerate(chosen):
                track.append(mido.Message("note_off", note=int(midi_notes[r]),
                                          velocity=0, time=tpb if i == 0 else 0))
            if not chosen:  # pauza
                track.append(mido.Message("note_off", note=0, velocity=0, time=tpb))
    mid.save(str(path))
    return True


