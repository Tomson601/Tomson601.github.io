    name = meta[k]["image"]
    url = f"https://epic.gsfc.nasa.gov/archive/{COLLECTION}/{y}/{m}/{d}/jpg/{name}.jpg"
    r = requests.get(url, timeout=60)
    r.raise_for_status()
    with open(f"{FRAMES_DIR}/{i:02d}_{name}.jpg", "wb") as f:
        f.write(r.content)
    print("Pobrano", name)



